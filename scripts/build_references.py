"""Build the skill's reference files from data/calques.jsonl.

Usage: python3 scripts/build_references.py
Writes skills/kazakh-without-calque/references/*.md. Low-confidence entries are left out
(they stay in data/calques.jsonl for review).
"""
import json
import os
from collections import defaultdict

OUT = "skills/kazakh-without-calque/references"

CATEGORIES = {
    "grammar": ("Grammar calques", "Case, possessive, tense and verb-form patterns copied from Russian."),
    "lexical": ("Word-choice calques", "Wrong word choice, or a term translated word for word from Russian."),
    "phrase": ("Phrase calques", "Multi-word expressions copied from Russian."),
    "bureaucratic": ("Officialese", "Bureaucratic clichés from Russian канцелярит."),
    "word-order": ("Word order", "Sentence structure and word order copied from Russian."),
    "style": ("Style", "Other naturalness and style issues."),
    "spelling": ("Spelling", "Common spelling and hyphenation errors (not calques)."),
}


def clean(s):
    return " ".join(str(s).split()).replace("|", "/")


def source_link(e):
    return f"[#{e['post']}]({e['source']})"


def pair_line(e):
    parts = []
    if e.get("wrong"):
        parts.append(f"❌ {clean(e['wrong'])}")
    if e.get("russian"):
        parts.append(f"⁉️ {clean(e['russian'])}")
    if e.get("correct"):
        parts.append("✅ " + " / ".join(clean(c) for c in e["correct"]))
    line = "- " + " · ".join(parts)
    if e.get("rule"):
        line += f" — {clean(e['rule'])}"
    return line + f" {source_link(e)}"


def main():
    entries = [json.loads(l) for l in open("data/calques.jsonl", encoding="utf-8")]
    entries = [e for e in entries if e.get("confidence") in ("high", "medium")]
    os.makedirs(OUT, exist_ok=True)

    pairs = defaultdict(list)
    rules = defaultdict(list)
    for e in entries:
        if e["kind"] == "rule":
            rules[e["category"]].append(e)
        elif e.get("correct"):
            pairs[e["category"]].append(e)

    header = (
        "<!-- Generated by scripts/build_references.py from data/calques.jsonl. Do not edit by hand. -->\n"
        "<!-- Source: «Калькасыз қазақ тілі» by Назгүл Қожабек, https://t.me/kalkastop -->\n\n"
    )

    counts = {}
    for cat, (title, desc) in CATEGORIES.items():
        items = sorted(pairs[cat], key=lambda e: clean(e.get("wrong") or e["correct"][0]).lower())
        counts[cat] = len(items)
        with open(f"{OUT}/{cat}.md", "w", encoding="utf-8") as f:
            f.write(header + f"# {title}\n\n{desc}\n\n")
            f.write("Format: ❌ calque · ⁉️ Russian source · ✅ natural Kazakh — why [#post](link)\n\n")
            f.write("\n".join(pair_line(e) for e in items) + "\n")

    with open(f"{OUT}/rules.md", "w", encoding="utf-8") as f:
        f.write(header + "# General rules\n\nPatterns explained by the author, with examples. "
                "Read the section that matches the construction you are unsure about.\n")
        for cat, (title, _) in CATEGORIES.items():
            if not rules[cat]:
                continue
            f.write(f"\n## {title}\n")
            for e in sorted(rules[cat], key=lambda e: e["post"]):
                f.write(f"\n### {clean(e.get('wrong') or e.get('rule', '')[:60])} {source_link(e)}\n\n")
                if e.get("rule"):
                    f.write(clean(e["rule"]) + "\n")
                if e.get("correct"):
                    f.write("\n✅ " + " / ".join(clean(c) for c in e["correct"]) + "\n")
                for ex in e.get("examples") or []:
                    if isinstance(ex, dict) and (ex.get("wrong") or ex.get("correct")):
                        f.write(f"\n- ❌ {clean(ex.get('wrong', ''))} → ✅ {clean(ex.get('correct', ''))}")
                f.write("\n")
    counts["rules"] = sum(len(v) for v in rules.values())
    print(counts)


if __name__ == "__main__":
    main()
